"""Streamlit interactive GlucoTwin synthetic demo."""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
import pandas as pd
import streamlit as st
from joblib import load
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.synthetic_data import generate_demo_patient, STATIC_COLS, LAG_COLS, DYNAMIC_COLS
from src.train import train_and_evaluate

ART = ROOT / "artifacts"
MODEL_PATH = ART / "synthetic_demo_model.joblib"
METRICS_PATH = ART / "synthetic_demo_metrics.json"

st.set_page_config(page_title="GlucoTwin Synthetic Demo", layout="wide")
st.title("GlucoTwin — Digital Twin Challenge Demo")
st.warning("SYNTHETIC DATA ONLY. This dashboard is a software demonstration, not a clinical tool. Do not use its probabilities for medical decisions.")

if not MODEL_PATH.exists() or not METRICS_PATH.exists():
    with st.spinner("Training the synthetic demonstration model…"):
        train_and_evaluate()
bundle = load(MODEL_PATH)
model = bundle["model"]
threshold = bundle["threshold"]
metrics = json.loads(METRICS_PATH.read_text(encoding="utf-8"))

patient_options = list(range(6))
patient_idx = st.selectbox("Synthetic patient", patient_options, format_func=lambda x: f"SYN-{x:03d}")
profile, cgm, meals = generate_demo_patient(patient_idx=patient_idx, seed=42, days=5)
max_t = len(cgm) - 5
if "time_idx" not in st.session_state:
    st.session_state.time_idx = min(96 * 3, max_t)
if st.button("Advance twin by 15 minutes"):
    st.session_state.time_idx = min(st.session_state.time_idx + 1, max_t)
t = st.slider("Current synthetic time index (15-minute steps)", 16, max_t, int(st.session_state.time_idx))
st.session_state.time_idx = t

history = cgm[t-15:t+1]
x = {k: profile[k] for k in STATIC_COLS}
x.update({f"cgm_lag_{i}": float(history[-1-i]) for i in range(16)})
x["cgm_mean_4h"] = float(np.mean(history))
x["cgm_std_4h"] = float(np.std(history))
x["cgm_slope_4h"] = float((history[-1] - history[0]) / 15.0)
x["meal_recent_4h"] = int(np.any(meals[max(0, t-15):t+1] == 1))
X = pd.DataFrame([[x[k] for k in bundle["feature_cols"]]], columns=bundle["feature_cols"])
prob = float(model.predict_proba(X)[0,1])
current = float(cgm[t])

m1, m2, m3, m4 = st.columns(4)
m1.metric("Current CGM (synthetic)", f"{current:.0f} mg/dL")
m2.metric("4-hour trend", f"{x['cgm_slope_4h']:+.1f} mg/dL / 15-min step")
m3.metric("Model probability", f"{prob:.0%}")
m4.metric("Demo threshold", f"{threshold:.2f}")
st.caption("The probability is generated by a model trained on generated synthetic trajectories. It is not calibrated or validated for real patients.")

left, right = st.columns([2,1])
with left:
    chart_df = pd.DataFrame({
        "CGM (mg/dL)": cgm[max(0,t-96):t+1],
        "Reference threshold (180)": np.full(len(cgm[max(0,t-96):t+1]), 180.0),
    }, index=np.arange(max(0,t-96), t+1))
    st.subheader("Recent synthetic CGM trajectory")
    st.line_chart(chart_df)
    st.caption("Reference line: 180 mg/dL. Chart values are simulated.")
with right:
    st.subheader("Synthetic patient profile")
    st.write({
        "Patient ID": profile["patient_id"],
        "Age": profile["age"],
        "BMI": profile["bmi"],
        "HbA1c": profile["hba1c"],
        "Diabetes duration (years)": profile["diabetes_duration_years"],
        "Glucose-lowering medication (simulated)": bool(profile["on_glucose_lowering_medication"]),
        "Meal event in last 4h (simulated)": bool(x["meal_recent_4h"]),
    })
    if t < len(cgm)-4 and current <= 180:
        actual = bool(np.any(cgm[t+1:t+5] > 180))
        st.write("Synthetic next-hour label (for demo inspection):", "Excursion" if actual else "No excursion")
    else:
        st.write("Current glucose is above the target threshold or the future window is incomplete.")

with st.expander("Synthetic-only training metrics"):
    st.json(metrics)
st.info("To claim challenge-level evidence, evaluate on the public ShanghaiT2DM dataset with strict patient-level separation. Synthetic metrics are included only to verify the end-to-end code path.")
