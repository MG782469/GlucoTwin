"""Train and evaluate a model on synthetic demo data only."""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.metrics import (
    roc_auc_score, average_precision_score, precision_score, recall_score,
    f1_score, brier_score_loss, confusion_matrix
)
from joblib import dump
from .synthetic_data import build_synthetic_windows, FEATURE_COLS

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "artifacts"
ART.mkdir(exist_ok=True)

def _safe_auc(y, p, metric):
    try:
        return float(metric(y, p))
    except Exception:
        return None

def train_and_evaluate(n_patients=100, days=5, seed=42):
    df = build_synthetic_windows(n_patients=n_patients, days=days, seed=seed)
    patient_ids = sorted(df["patient_id"].unique())
    rng = np.random.default_rng(seed)
    rng.shuffle(patient_ids)
    n_train = int(len(patient_ids) * 0.70)
    n_val = int(len(patient_ids) * 0.15)
    train_ids = set(patient_ids[:n_train])
    val_ids = set(patient_ids[n_train:n_train+n_val])
    test_ids = set(patient_ids[n_train+n_val:])
    train = df[df.patient_id.isin(train_ids)]
    val = df[df.patient_id.isin(val_ids)]
    test = df[df.patient_id.isin(test_ids)]
    # Keep validation distinct and use it only to choose a simple probability threshold.
    X_train, y_train = train[FEATURE_COLS], train["label"]
    X_val, y_val = val[FEATURE_COLS], val["label"]
    X_test, y_test = test[FEATURE_COLS], test["label"]
    model = HistGradientBoostingClassifier(
        max_iter=100, learning_rate=0.08, max_leaf_nodes=15,
        l2_regularization=1.0, random_state=seed
    )
    model.fit(X_train, y_train)
    p_val = model.predict_proba(X_val)[:, 1]
    # Threshold selection on validation set: maximize F1 (demo only).
    thresholds = np.linspace(0.15, 0.85, 29)
    best_threshold = 0.5
    best_f1 = -1.0
    for th in thresholds:
        pred = (p_val >= th).astype(int)
        score = f1_score(y_val, pred, zero_division=0)
        if score > best_f1:
            best_f1, best_threshold = float(score), float(th)
    p_test = model.predict_proba(X_test)[:, 1]
    pred_test = (p_test >= best_threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_test, pred_test, labels=[0,1]).ravel()
    baseline_pred = (test["current_glucose"].to_numpy() >= 165).astype(int)
    metrics = {
        "evidence_status": "SYNTHETIC DEMO ONLY — NOT CLINICAL PERFORMANCE",
        "n_patients_synthetic": int(df.patient_id.nunique()),
        "n_windows_synthetic": int(len(df)),
        "train_patients": len(train_ids),
        "validation_patients": len(val_ids),
        "test_patients": len(test_ids),
        "positive_label_rate_all_windows": float(df.label.mean()),
        "model": "HistGradientBoostingClassifier",
        "threshold_selected_on_validation": best_threshold,
        "test_auroc_synthetic": _safe_auc(y_test, p_test, roc_auc_score),
        "test_auprc_synthetic": _safe_auc(y_test, p_test, average_precision_score),
        "test_precision_synthetic": float(precision_score(y_test, pred_test, zero_division=0)),
        "test_sensitivity_synthetic": float(recall_score(y_test, pred_test, zero_division=0)),
        "test_specificity_synthetic": float(tn / (tn + fp)) if (tn+fp) else None,
        "test_f1_synthetic": float(f1_score(y_test, pred_test, zero_division=0)),
        "test_brier_synthetic": float(brier_score_loss(y_test, p_test)),
        "test_confusion_matrix": {"tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp)},
        "baseline_threshold_165_precision_synthetic": float(precision_score(y_test, baseline_pred, zero_division=0)),
        "baseline_threshold_165_sensitivity_synthetic": float(recall_score(y_test, baseline_pred, zero_division=0)),
        "note": "Labels and signals are generated by src/synthetic_data.py. These metrics verify the pipeline only and must not be described as clinical accuracy."
    }
    dump({"model": model, "feature_cols": FEATURE_COLS, "threshold": best_threshold}, ART / "synthetic_demo_model.joblib")
    (ART / "synthetic_demo_metrics.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    return metrics

if __name__ == "__main__":
    m = train_and_evaluate()
    print(json.dumps(m, indent=2))
